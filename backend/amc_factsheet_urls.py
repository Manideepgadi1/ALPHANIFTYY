def get_amc_factsheet_url(fund_house_name):
    """
    Get the factsheet URL for a given fund house
    
    Args:
        fund_house_name: Name of the fund house (e.g., "HDFC Mutual Fund")
    
    Returns:
        URL string to the fund house's factsheet page
    """
    if not fund_house_name:
        return AMC_FACTSHEET_URLS['DEFAULT']
    
    # Try exact match first
    if fund_house_name in AMC_FACTSHEET_URLS:
        return AMC_FACTSHEET_URLS[fund_house_name]
    
    # Try partial match (e.g., "HDFC Top 100 Fund" -> "HDFC")
    for amc_key in AMC_FACTSHEET_URLS.keys():
        if amc_key != 'DEFAULT' and amc_key.lower() in fund_house_name.lower():
            return AMC_FACTSHEET_URLS[amc_key]
    
    # Fallback to AMFI
    return AMC_FACTSHEET_URLS['DEFAULT']


def extract_fund_house_from_name(fund_name):
    """
    Extract fund house name from full scheme name
    
    Args:
        fund_name: Full fund name (e.g., "HDFC Top 100 Fund-Reg(G)")
    
    Returns:
        Fund house name (e.g., "HDFC")
    """
    if not fund_name:
        return None
    
    # Common patterns:
    # "HDFC Top 100 Fund-Reg(G)" -> "HDFC"
    # "Axis Bluechip Fund" -> "Axis"
    
    # Split by space and take first 2-3 words
    parts = fund_name.split()
    if len(parts) >= 2:
        # Check if it's a known AMC prefix
        prefix_2 = ' '.join(parts[:2])
        prefix_3 = ' '.join(parts[:3]) if len(parts) >= 3 else None
        
        if prefix_3 and prefix_3 in AMC_FACTSHEET_URLS:
            return prefix_3
        if prefix_2 in AMC_FACTSHEET_URLS:
            return prefix_2
        if parts[0] in AMC_FACTSHEET_URLS:
            return parts[0]
    
    # Try splitting by dash
    if '-' in fund_name:
        prefix = fund_name.split('-')[0].strip()
        words = prefix.split()
        if len(words) >= 1:
            if words[0] in AMC_FACTSHEET_URLS:
                return words[0]
    
    return parts[0] if parts else None
